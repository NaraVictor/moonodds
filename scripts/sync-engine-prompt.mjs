#!/usr/bin/env node
/**
 * Inject src/lib/engine/prompt.ts into supabase/seed.sql.
 *
 * The prompt has to exist in two places, TypeScript, so the app can reset a
 * config back to it, and SQL, so a fresh `supabase db reset` seeds it. Two
 * hand-maintained copies of a 20KB document drift within a week, and the
 * failure is invisible: the app shows one prompt, the engine runs the other.
 *
 * So one is generated from the other, written between markers in seed.sql.
 * A separate file included with psql's \ir would be tidier, but the Supabase
 * CLI sends the seed to the server as one batch and never interprets client-side
 * meta-commands, \ir arrives at Postgres verbatim and fails on the backslash.
 *
 * Usage:
 *   node scripts/sync-engine-prompt.mjs           write into seed.sql
 *   node scripts/sync-engine-prompt.mjs --check   verify it is current
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "src/lib/engine/prompt.ts");
const TARGET = join(root, "supabase/seed.sql");
const VARIABLES = join(root, "src/lib/engine/variables.ts");

const START = "-- ENGINE PROMPT START";
const END = "-- ENGINE PROMPT END";

/** Pull the template literal out without executing any TypeScript. */
function extractTemplate(source) {
  const marker = "export const ENGINE_PROMPT_TEMPLATE = `";
  const start = source.indexOf(marker);
  if (start === -1) throw new Error("ENGINE_PROMPT_TEMPLATE not found in prompt.ts");
  const from = start + marker.length;
  const end = source.indexOf("`;", from);
  if (end === -1) throw new Error("Unterminated ENGINE_PROMPT_TEMPLATE literal");
  return source.slice(from, end);
}

function extractVersion(source) {
  const match = source.match(/ENGINE_PROMPT_VERSION\s*=\s*"([^"]+)"/);
  if (!match) throw new Error("ENGINE_PROMPT_VERSION not found in prompt.ts");
  return match[1];
}

const promptSource = readFileSync(SOURCE, "utf8");
const template = extractTemplate(promptSource);
const version = extractVersion(promptSource);

// Every placeholder must have a definition, or the prompt cannot render and the
// daily run throws. Cheaper to fail here than at 04:00 UTC.
const defined = new Set(
  [...readFileSync(VARIABLES, "utf8").matchAll(/^\s*\{ key: "([a-zA-Z0-9_]+)"/gm)].map((m) => m[1]),
);
const used = [...new Set([...template.matchAll(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g)].map((m) => m[1]))];
const missing = used.filter((k) => !defined.has(k));
if (missing.length) {
  console.error(`Prompt references ${missing.length} undefined variable(s): ${missing.join(", ")}`);
  process.exit(1);
}

// Dollar-quoted so the prompt's own apostrophes need no escaping. The tag is
// unusual enough that the prompt text will never contain it.
const block = `${START}, generated by \`pnpm engine:sync\` from
-- src/lib/engine/prompt.ts (prompt version ${version}, ${used.length} variables).
-- Everything between these markers is overwritten; edit the TypeScript source.

update ai_engine_config
set system_prompt = $moonodds_prompt$${template}$moonodds_prompt$,
    last_updated_at = now()
where id = 'c0000001-0000-4000-8000-000000000001';

${END}`;

const seed = readFileSync(TARGET, "utf8");
const start = seed.indexOf(START);
const end = seed.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error(`Could not find the ${START} / ${END} markers in supabase/seed.sql.`);
  process.exit(1);
}

const next = seed.slice(0, start) + block + seed.slice(end + END.length);

if (process.argv.includes("--check")) {
  if (seed !== next) {
    console.error("seed.sql prompt block is stale, prompt.ts has changed. Run: pnpm engine:sync");
    process.exit(1);
  }
  console.log(`seed.sql prompt block is current (v${version}, ${used.length} variables).`);
  process.exit(0);
}

writeFileSync(TARGET, next);
console.log(`Updated supabase/seed.sql, prompt v${version}, ${used.length} variables.`);
